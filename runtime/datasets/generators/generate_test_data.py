#!/usr/bin/env python3
"""
Generate test data for the Java backend.

Produces deterministic fixture files (JSON + SQL) that the Java Service / DAO
layer can consume in unit tests, integration tests, and seed scripts.

Outputs (under --outdir, default ./out):
  test_data.json   — main record set (one JSON object per entity)
  test_data.csv    — tabular view for mock/DAO parameterized tests
  seed.sql         — INSERT statements for a persistent DB-backed integration test

Fully offline and dependency-free (stdlib only). Usage:

    python3 generate_test_data.py --records 50 --outdir out --seed 42
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Iterable

ENTITY = "InterviewStatus"
FIELDS: tuple[str, ...] = (
    "id",
    "candidate",
    "role",
    "stage",
    "score",
    "status",
    "created_at",
)

STAGES = ("SCREENING", "TECHNICAL", "SYSTEM_DESIGN", "BEHAVIOURAL", "OFFER")
STATUSES = ("SCHEDULED", "IN_PROGRESS", "COMPLETED", "REJECTED")


def _utcnow() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def _slug(candidate: str) -> str:
    return hashlib.sha1(candidate.encode("utf-8")).hexdigest()[:8]


def _mk_record(seed: int, idx: int) -> dict[str, Any]:
    candidate = f"candidate-{idx:04d}"
    score = round(random.uniform(0.0, 100.0), 2)
    stage = random.choice(STAGES)
    status = "COMPLETED" if stage == "OFFER" else random.choice(STATUSES)
    status = "COMPLETED" if stage == "OFFER" else random.choice(STATUSES)
    created = _fake_timestamp(seed, idx)
    record_id = f"{entity_id(seed, idx)}"

    return {
        "id": record_id,
        "candidate": candidate,
        "role": "Backend Engineer",
        "stage": stage,
        "score": score,
        "status": status,
        "created_at": created,
        "_slug": _slug(candidate),
    }


def _fake_timestamp(seed: int, idx: int) -> str:
    """Deterministic ISO-8601 timestamp anchored to a fixed epoch."""
    base = datetime(2024, 1, 1, tzinfo=timezone.utc)
    shift = idx * 3600 + (seed % 60)
    return (base + timedelta(seconds=shift)).isoformat(timespec="milliseconds")


def entity_id(seed: int, idx: int) -> str:
    raw = f"{seed}:{idx}:{ENTITY}"
    return f"{ENTITY}-{hashlib.sha1(raw.encode('utf-8')).hexdigest()[:12]}"


def generate(records: int, seed: int) -> list[dict[str, Any]]:
    random.seed(seed)
    return [_mk_record(seed, i) for i in range(records)]


def write_json(rows: list[dict[str, Any]], path: Path) -> None:
    path.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    columns = [c for c in FIELDS if c != "id"] + ["id"]
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=columns)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k) for k in columns})


def write_sql(rows: list[dict[str, Any]], table: str, path: Path) -> None:
    lines = [
        f"-- Generated by generate_test_data.py ({_utcnow()})",
        f"-- Table: {table}  |  Rows: {len(rows)}",
        f"INSERT INTO {table} ({', '.join(FIELDS)}) VALUES",
    ]
    tuples = [
        ", ".join(
            [
                f"'{r['id']}'",
                f"'{r['candidate']}'",
                f"'{r['role']}'",
                f"'{r['stage']}'",
                f"{r['score']}",
                f"'{r['status']}'",
                f"'{r['created_at']}'",
            ]
        )
        for r in rows
    ]
    lines.append(",\n".join(f"({t})" for t in tuples))
    lines.append(";")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _validate(rows: list[dict[str, Any]], records: int) -> None:
    unique = {r["id"] for r in rows}
    assert len(unique) == records, "generated IDs must be unique"
    for r in rows:
        assert r["stage"] in STAGES
        assert r["status"] in STATUSES
        assert 0.0 <= r["score"] <= 100.0
        assert r["created_at"].endswith("Z") or "+00:00" in r["created_at"]


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--records", type=int, default=50, help="number of records")
    parser.add_argument("--seed", type=int, default=42, help="RNG seed (determinism)")
    parser.add_argument("--outdir", type=str, default="out", help="output directory")
    parser.add_argument("--table", type=str, default=ENTITY, help="SQL table name")
    args = parser.parse_args(argv)

    if args.records < 1:
        parser.error("--records must be >= 1")

    rows = generate(args.records, args.seed)
    _validate(rows, args.records)

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    write_json(rows, outdir / "test_data.json")
    write_csv(rows, outdir / "test_data.csv")
    write_sql(rows, args.table, outdir / "seed.sql")

    print(json.dumps(
        {"status": "ok", "entity": ENTITY, "records": len(rows), "seed": args.seed,
         "outputs": [p.name for p in outdir.glob("*")], "outdir": str(outdir)},
        indent=2,
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())