# C. Hypothesis Retrieval Lane — two-pass retrieval
# =============================================================================

class TestHypothesisRetrievalLane(unittest.TestCase):
    """Hypotheses must be retrievable without being promoted to established memory."""

    def test_hypothesis_has_separate_lane(self):
        """Hypothesis results must be distinguishable from established results."""
        query = {
            "task_text": "Analyze backend service performance",
            "category": "backend",
            "domains": ["backend"],
            "roles": ["backend-architect"],
            "keywords": ["backend", "performance"],
            "difficulty": "medium",
            "exclude_hypothesis": False,
        }

        result = retrieve(query)
        results = result.get("results", [])

        for r in results:
            if r.get("is_hypothesis"):
                # Hypotheses must be labeled as such
                self.assertTrue(r.get("is_hypothesis"), f"Memory {r['memory_id']} should be labeled as hypothesis")
                # Hypotheses must have a warning about unvalidated status
                if r.get("warning"):
                    self.assertIn("Unvalidated", r["warning"])

    def test_hypothesis_not_auto_promoted_to_established(self):
        """Retrieval lane must not change hypothesis type to established."""
        index = load_memory_index()
        memories = index.get("memories", [])

        hypothesis_ids = [m["memory_id"] for m in memories if m.get("type") == "hypothesis"]
        if not hypothesis_ids:
            self.skipTest("No hypotheses to test")

        test_id = hypothesis_ids[0]
        h_mem = next(m for m in memories if m["memory_id"] == test_id)

        query = {
            "task_text": "Test retrieval for hypothesis",
            "category": h_mem.get("category", "backend"),
            "domains": h_mem.get("tags", []),
            "roles": h_mem.get("roles", []),
            "keywords": h_mem.get("tags", []),
            "difficulty": "medium",
            "exclude_hypothesis": False,
        }

        result = retrieve(query)
        for r in result.get("results", []):
            if r["memory_id"] == test_id:
                self.assertEqual(r.get("type"), "hypothesis",
                                 f"Hypothesis {test_id} must remain type='hypothesis', got {r.get('type')}")
                self.assertTrue(r.get("is_hypothesis"),
                                f"is_hypothesis flag must be True for {test_id}")

    def test_ranking_test_hypothesis_visible(self):
        """At least one hypothesis must appear in retrieval results when relevant."""
        query = {
            "task_text": "Build a backend service with state management",
            "category": "backend",
            "domains": ["backend", "state"],
            "roles": ["backend-architect", "backend-engineer"],
            "keywords": ["backend", "state", "session"],
            "difficulty": "medium",
            "exclude_hypothesis": False,
        }

        result = retrieve(query)
        results = result.get("results", [])
        hypothesis_results = [r for r in results if r.get("is_hypothesis")]

        # Not all queries will match hypotheses, but we verify the structure
        for h in hypothesis_results:
            self.assertIsNotNone(h.get("static_relevance"),
                                 f"Hypothesis {h['memory_id']} missing static_relevance")
            self.assertIsNotNone(h.get("final_score"),
                                 f"Hypothesis {h['memory_id']} missing final_score")


