# D. Validation Aggregation — cross-run observation
# =============================================================================

class TestValidationAggregation(unittest.TestCase):
    """Cross-loop observation accumulation must drive validation."""

    def setUp(self):
        self.loop_id_r1 = "LOOP-VALIDATE-R1"
        self.loop_id_r2 = "LOOP-VALIDATE-R2"

    def test_group_candidates_aggregates_executions(self):
        """Multiple candidates for same memory must aggregate executions."""
        candidates = [
            _make_candidate_fixture("H-AGG-001", "EXEC-R1", loop_id=self.loop_id_r1),
            _make_candidate_fixture("H-AGG-001", "EXEC-R2", loop_id=self.loop_id_r2),
        ]

        groups = group_candidates_by_memory(candidates)
        self.assertIn("H-AGG-001", groups)

        group = groups["H-AGG-001"]
        self.assertEqual(len(group["executions"]), 2,
                         f"Expected 2 executions, got {len(group['executions'])}")
        self.assertIn("EXEC-R1", group["executions"])
        self.assertIn("EXEC-R2", group["executions"])

    def test_single_observation_enters_as_hypothesis(self):
        """H-xxx with 1 observation enters as hypothesis, not validated."""
        candidates = [
            _make_candidate_fixture("H-SINGLE-001", "EXEC-S1", loop_id=self.loop_id_r1),
        ]

        groups = group_candidates_by_memory(candidates)
        status, result = validate_memory_group("H-SINGLE-001", groups["H-SINGLE-001"])

        self.assertEqual(status, "hypothesis",
                         f"Single observation H-xxx should be 'hypothesis', got '{status}'")
        self.assertEqual(result["validation_runs"], 1)

    def test_two_observations_graduates_to_validated(self):
        """H-xxx with 2 observations must graduate to validated."""
        candidates = [
            _make_candidate_fixture("H-GRAD-001", "EXEC-G1", loop_id=self.loop_id_r1),
            _make_candidate_fixture("H-GRAD-001", "EXEC-G2", loop_id=self.loop_id_r2),
        ]

        groups = group_candidates_by_memory(candidates)
        status, result = validate_memory_group("H-GRAD-001", groups["H-GRAD-001"])

        self.assertEqual(status, "validated",
                         f"Two-observation H-xxx should be 'validated', got '{status}'")
        self.assertEqual(result["validation_runs"], 2)

    def test_observation_log_enriches_groups(self):
        """Observation log entries must enrich cross-loop groups."""
        # Write a test observation log
        test_log = {
            "version": "1.0",
            "observations": [
                {
                    "memory_id": "H-ENRICH-001",
                    "source_loop": "LOOP-PREVIOUS-001",
                    "source_execution": "EXEC-PREV",
                    "session_id": "sess-prev",
                    "output_hash": "hash123",
                    "quality_score": 4.0,
                    "candidate_type": "reinforce",
                    "observed_at": datetime.now(timezone.utc).isoformat(),
                    "origin": "runtime",
                },
            ],
        }

        with tempfile.NamedTemporaryFile(mode="w", suffix=".yaml", delete=False) as f:
            obs_path = f.name
            yaml.dump(test_log, f)

        try:
            import validator
            original = validator.OBSERVATION_LOG_FILE
            validator.OBSERVATION_LOG_FILE = obs_path

            # Create a group with 1 current candidate + 1 observation log entry
            candidates = [
                _make_candidate_fixture("H-ENRICH-001", "EXEC-NOW", loop_id=self.loop_id_r1),
            ]
            groups = group_candidates_by_memory(candidates)
            enriched = enrich_groups_with_observation_log(groups)

            self.assertIn("H-ENRICH-001", enriched)
            group = enriched["H-ENRICH-001"]

            # Should have 2 executions (1 from candidate + 1 from observation log)
            self.assertEqual(len(group["executions"]), 2,
                             f"Expected 2 executions after enrichment, got {len(group['executions'])}")

            validator.OBSERVATION_LOG_FILE = original
        finally:
            os.unlink(obs_path)


