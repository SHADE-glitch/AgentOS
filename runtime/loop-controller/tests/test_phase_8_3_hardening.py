# A. Artifact Authority — loop_id consistency
# =============================================================================

class TestArtifactAuthority(unittest.TestCase):
    """All runtime artifacts from the same run must share the same loop_id."""

    def setUp(self):
        self.loop_id = "LOOP-ARTIFACT-001"
        self.tmpdir = tempfile.mkdtemp()

    def test_candidate_loop_id_set(self):
        """Candidates generated by collector must carry loop_id."""
        candidates = []
        for i in range(3):
            c = _make_candidate_fixture(f"H-TEST-{i}", f"EXEC-{i}", loop_id=self.loop_id)
            candidates.append(c)

        for c in candidates:
            self.assertEqual(c["loop_id"], self.loop_id,
                             f"Candidate {c['candidate_id']} missing correct loop_id")

    def test_candidate_loop_id_consistency(self):
        """All candidates from same run must have the same loop_id."""
        candidates = [
            _make_candidate_fixture("H-A", "EXEC-1", loop_id=self.loop_id),
            _make_candidate_fixture("H-B", "EXEC-2", loop_id=self.loop_id),
            _make_candidate_fixture("H-C", "EXEC-3", loop_id=self.loop_id),
        ]

        unique_loop_ids = set(c["loop_id"] for c in candidates)
        self.assertEqual(len(unique_loop_ids), 1,
                         f"Expected 1 loop_id, got {len(unique_loop_ids)}: {unique_loop_ids}")
        self.assertEqual(unique_loop_ids.pop(), self.loop_id)

    def test_validator_passes_loop_id(self):
        """Validator must stamp loop_id on each result."""
        candidates = [
            _make_candidate_fixture("H-001-TEST", "EXEC-A", loop_id=self.loop_id),
            _make_candidate_fixture("H-001-TEST", "EXEC-B", loop_id=self.loop_id),
        ]
        results = validate_candidates(candidates, quiet=True, loop_id=self.loop_id)

        for r in results:
            self.assertEqual(r.get("loop_id"), self.loop_id,
                             f"Validation result for {r['memory_id']} missing loop_id")

    def test_promoter_provenance_has_loop_id(self):
        """Promotion result must include provenance with loop_id."""
        validated_result = {
            "memory_id": "H-001-TEST",
            "best_candidate_id": "CAND-EXEC-A-H-001-TEST",
            "status": "validated",
            "validation_runs": 2,
            "quality_score": 4.5,
            "confidence": 0.4,
            "evidence_sources": ["EXEC-A", "EXEC-B"],
            "gate_results": {"M1_provenance": "pass"},
        }

        result = promote_validated(validated_result, loop_id=self.loop_id)

        if result["status"] == "applied":
            self.assertIn("provenance", result, "Applied result must have provenance")
            self.assertEqual(result["provenance"]["loop_id"], self.loop_id)
            self.assertIn("observation_sources", result["provenance"])
            self.assertIn("observation_count", result["provenance"])

    def test_retrieval_history_has_loop_id(self):
        """Retrieval history entries must record loop_id."""
        query = {"task_text": "test task", "category": "backend"}
        result = {"results": []}

        with tempfile.NamedTemporaryFile(mode="w", suffix=".yaml", delete=False) as f:
            tmp_path = f.name
            yaml.dump({"version": "1.0", "phase": "5.8", "retrievals": []}, f)

        try:
            import retrieval_optimizer as ro
            original = ro.RETRIEVAL_HISTORY
            ro.RETRIEVAL_HISTORY = tmp_path

            save_retrieval_history(query, result, loop_id=self.loop_id)

            with open(tmp_path) as f:
                saved = yaml.safe_load(f)

            self.assertGreater(len(saved.get("retrievals", [])), 0)
            self.assertEqual(saved["retrievals"][-1]["loop_id"], self.loop_id)

            ro.RETRIEVAL_HISTORY = original
        finally:
            os.unlink(tmp_path)

    def test_write_candidates_output_has_loop_id(self):
        """write_candidates_output must include loop_id in YAML output."""
        candidates = [_make_candidate_fixture("H-TEST", "EXEC-1", loop_id=self.loop_id)]

        with tempfile.NamedTemporaryFile(mode="r", suffix=".yaml", delete=False) as f:
            tmp_path = f.name

        try:
            import collector as col
            original = col.CANDIDATES_FILE
            col.CANDIDATES_FILE = tmp_path

            write_candidates_output(candidates, ["EXEC-1"], loop_id=self.loop_id)

            with open(tmp_path) as f:
                saved = yaml.safe_load(f)

            self.assertEqual(saved.get("loop_id"), self.loop_id)
            self.assertEqual(saved["candidates"][0]["loop_id"], self.loop_id)

            col.CANDIDATES_FILE = original
        finally:
            os.unlink(tmp_path)


