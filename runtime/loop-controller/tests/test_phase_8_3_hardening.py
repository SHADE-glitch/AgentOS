# B. Cross-loop Memory Lineage — Run 1 → Run 2 retrieval
# =============================================================================

class TestCrossLoopMemoryLineage(unittest.TestCase):
    """Hypothesis created in Run 1 must be retrievable in Run 2."""

    def setUp(self):
        self.loop_id_r1 = "LOOP-RUN1-001"
        self.loop_id_r2 = "LOOP-RUN2-001"

    def test_hypothesis_survives_across_runs(self):
        """Run 1 hypothesis is present in retrieval index and can be retrieved by Run 2."""
        index = load_memory_index()
        memories = index.get("memories", [])

        hypothesis_ids = [m["memory_id"] for m in memories if m.get("type") == "hypothesis"]
        self.assertGreater(len(hypothesis_ids), 0,
                           "No hypotheses exist in retrieval index — cannot test cross-run lineage")

        # Pick a hypothesis with strong keyword overlap for a realistic query
        # Use a hypothesis with tags that match a common backend/state query
        test_hyp_id = hypothesis_ids[0]
        h_mem = next(m for m in memories if m["memory_id"] == test_hyp_id)

        # Simulate Run 2: query related to the hypothesis domain
        query = {
            "task_text": "Debug session state inconsistency in Java service",
            "category": h_mem.get("category", "backend"),
            "domains": h_mem.get("tags", []),
            "roles": h_mem.get("roles", []),
            "keywords": h_mem.get("tags", []),
            "difficulty": "medium",
            "exclude_hypothesis": False,
        }

        result = retrieve(query)

        hypothesis_retrieved = [r for r in result.get("results", []) if r.get("is_hypothesis")]
        self.assertGreater(len(hypothesis_retrieved), 0,
                           f"Run 2 must retrieve at least 1 hypothesis. "
                           f"Query: {query['task_text'][:60]} — "
                           f"Total results: {len(result.get('results', []))}")

    def test_hypothesis_retrieved_for_similar_task(self):
        """Relevant hypothesis should appear when querying a similar task."""
        index = load_memory_index()
        memories = index.get("memories", [])

        # Find a hypothesis with a specific category
        backend_hypotheses = [m for m in memories
                               if m.get("type") == "hypothesis"
                               and m.get("category") == "backend"]
        if not backend_hypotheses:
            backend_hypotheses = [m for m in memories if m.get("type") == "hypothesis"]

        self.assertGreater(len(backend_hypotheses), 0, "No hypotheses to test similarity retrieval")

        h = backend_hypotheses[0]
        tags = h.get("tags", ["backend"])

        query = {
            "task_text": f"Fix issues in the same area: {tags[0] if tags else 'backend'}",
            "category": h.get("category", "backend"),
            "domains": tags,
            "roles": h.get("roles", []),
            "keywords": tags,
            "difficulty": "medium",
            "exclude_hypothesis": False,
        }

        result = retrieve(query)
        hypothesis_results = [r for r in result.get("results", []) if r.get("is_hypothesis")]

        self.assertGreater(len(hypothesis_results), 0,
                           f"Similarity query returned zero hypotheses. "
                           f"tags: {tags}, category: {h.get('category')}")

    def test_retrieval_returns_established_and_hypothesis_separately(self):
        """Retrieval must return both established and hypothesis results."""
        query = {
            "task_text": "Design a backend system with persistence",
            "category": "backend",
            "domains": ["backend", "database"],
            "roles": ["backend-architect"],
            "keywords": ["backend", "database"],
            "difficulty": "medium",
            "exclude_hypothesis": False,
        }

        result = retrieve(query)
        results = result.get("results", [])

        established = [r for r in results if not r.get("is_hypothesis")]
        hypothesis = [r for r in results if r.get("is_hypothesis")]

        # At minimum, we should have some results with established memories
        self.assertGreaterEqual(len(results), 0,
                                "Retrieval should return results (may be empty if no match)")


