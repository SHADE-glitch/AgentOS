# E. Promotion Provenance — validated_ids → promoted_ids
# =============================================================================

class TestPromotionProvenance(unittest.TestCase):
    """Promotion must be driven by runtime evidence with complete provenance chain."""

    def setUp(self):
        self.loop_id = "LOOP-PROMOTE-001"

    def test_promotion_result_has_provenance(self):
        """Valid promotion result must include provenance field."""
        validated_result = {
            "memory_id": "H-PROV-001",
            "best_candidate_id": "CAND-EXEC-PROV-H-PROV-001",
            "status": "validated",
            "validation_runs": 2,
            "quality_score": 4.5,
            "confidence": 0.4,
            "evidence_sources": ["EXEC-P1", "EXEC-P2"],
            "gate_results": {"M1_provenance": "pass"},
        }

        result = promote_validated(validated_result, loop_id=self.loop_id)

        if result["status"] == "applied":
            prov = result.get("provenance", {})
            self.assertEqual(prov.get("loop_id"), self.loop_id,
                             "Provenance must track the loop that triggered promotion")
            self.assertIn("source_validation_ids", prov,
                          "Provenance must list source validation IDs")
            self.assertIn("observation_sources", prov,
                          "Provenance must list observation sources")
            self.assertIn("observation_count", prov,
                          "Provenance must track observation count")

    def test_provenance_chain_traceable(self):
        """Provenance must connect validated_ids back to evidence sources."""
        validated_result = {
            "memory_id": "H-CHAIN-001",
            "best_candidate_id": "CAND-EXEC-CHAIN-H-CHAIN-001",
            "status": "validated",
            "validation_runs": 3,
            "quality_score": 4.8,
            "confidence": 0.6,
            "evidence_sources": ["EXEC-C1", "EXEC-C2", "EXEC-C3"],
            "gate_results": {"M1_provenance": "pass"},
        }

        result = promote_validated(validated_result, loop_id=self.loop_id)

        if result["status"] == "applied":
            prov = result["provenance"]
            self.assertEqual(prov["observation_count"], 3,
                             f"Expected 3 observations, got {prov['observation_count']}")
            self.assertEqual(len(prov["observation_sources"]), 3)
            self.assertIn("EXEC-C1", prov["observation_sources"])
            self.assertIn("EXEC-C2", prov["observation_sources"])
            self.assertIn("EXEC-C3", prov["observation_sources"])

    def test_evidence_updates_track_delta(self):
        """Promotion result must track old→new evidence evolution."""
        validated_result = {
            "memory_id": "H-DELTA-001",
            "best_candidate_id": "CAND-EXEC-DELTA-H-DELTA-001",
            "status": "validated",
            "validation_runs": 2,
            "quality_score": 4.2,
            "confidence": 0.4,
            "evidence_sources": ["EXEC-D1", "EXEC-D2"],
            "gate_results": {"M1_provenance": "pass"},
        }

        result = promote_validated(validated_result, loop_id=self.loop_id)

        if result["status"] == "applied":
            self.assertIn("evidence_updates", result,
                          "Applied result must have evidence_updates")
            updates = result["evidence_updates"]
            self.assertIn("old_observation_count", updates)
            self.assertIn("new_observation_count", updates)
            self.assertIn("old_evidence_level", updates)
            self.assertIn("new_evidence_level", updates)

    def test_promotion_idempotency(self):
        """Re-promoting same memory should be skipped, not duplicated."""
        validated_result = {
            "memory_id": "H-IDEM-001",
            "best_candidate_id": "CAND-EXEC-IDEM-H-IDEM-001",
            "status": "validated",
            "validation_runs": 2,
            "quality_score": 4.0,
            "confidence": 0.4,
            "evidence_sources": ["EXEC-I1", "EXEC-I2"],
            "gate_results": {"M1_provenance": "pass"},
        }

        result = promote_validated(validated_result, loop_id=self.loop_id)

        # If skipped (because already promoted), that's acceptable
        if result["status"] == "skipped":
            self.assertIn("rejection_reason", result)
            self.assertIn("idempotency", result["rejection_reason"].lower())
        elif result["status"] == "applied":
            self.assertIn("provenance", result)


